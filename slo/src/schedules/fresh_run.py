"""Fresh-run invoker — the process-start owner for fresh schedules (111.a.3 §3.2, D5.1).

`FreshRunInvoker` spawns one headless ``slo run`` child per invocation and waits
for it. `FreshRunCommand` is the one owner of the child command line, working
directory, executable lookup and environment; `SubprocessFreshRunLauncher` owns
the OS process mechanics, including reaping the child when the delivery is
cancelled (a lost delivery lease must not orphan the run).
"""

from __future__ import annotations

import asyncio
import os
import re
import shutil
import sys
from collections.abc import Callable
from contextlib import suppress
from pathlib import Path
from typing import Literal, Optional, Protocol

from pydantic import BaseModel, ConfigDict, Field

__all__ = [
    "FreshRunCommand",
    "FreshRunInvoker",
    "FreshRunLauncher",
    "FreshRunResultDAO",
    "SubprocessFreshRunLauncher",
    "UnsupportedFreshRunWrapperError",
]

_REAP_GRACE_SECONDS: float = 5.0

# The exact user-facing wrapper ``install.sh:slo_render_isolated_launcher``
# writes. It already starts the pinned interpreter with ``-I``.
_INSTALLER_LAUNCHER_HEADER: tuple[str, str, str] = (
    "#!/bin/sh",
    "# >>> slo isolated launcher (v1) >>>",
    "# Generated by the Slo installer; do not edit.",
)
_INSTALLER_LAUNCHER_EXEC: re.Pattern[str] = re.compile(r"""^exec '(/[^']+)' -I '(/[^']+)' "\$@"$""")
# A packaging-generated console script: an absolute python interpreter,
# optionally with the ``-E`` flag pip/pipx may emit (``-I`` implies it).
_CONSOLE_SCRIPT_SHEBANG: re.Pattern[str] = re.compile(r"^#!(/\S*/python[\w.]*)(?: -E)?$")


class UnsupportedFreshRunWrapperError(RuntimeError):
    """The resolved ``slo`` wrapper does not carry the import-isolation contract."""


class FreshRunResultDAO(BaseModel):
    """Result of one headless fresh run."""

    model_config = ConfigDict(frozen=True)

    session_id: str = Field(
        description="Session the run created: str(uuid4()), new per due time. Same type as recipient_session_id."
    )
    exit_code: int = Field(description="Child process exit code.")
    status: Literal["completed", "run_failed"] = Field(
        description="completed for exit code 0, else run_failed."
    )


class FreshRunLauncher(Protocol):
    """Spawns one headless child process and returns its exit code."""

