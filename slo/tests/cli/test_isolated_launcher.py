"""Functional contracts for the isolated pipx user launcher."""

from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path

from tests.cli.test_install import FakeBin


def _write_entry_launcher(*, path: Path, python_bin: Path) -> None:
    """Write a generated-style trampoline that probes isolated process state.

    Args:
        path (Path): Destination entry launcher path.
        python_bin (Path): Interpreter named by the generated script shebang.
    """
    path.write_text(
        f"#!{python_bin}\n"
        "# from src.cli import main\n"
        "import json\n"
        "import os\n"
        "import sys\n"
        "print(json.dumps({'path': sys.path, 'slo_home': os.environ.get('SLO_HOME'), "
        "'skills_dir': os.environ.get('SLO_SKILLS_DIR'), 'kb_dir': os.environ.get('SLO_KB_DIR'), "
        "'credential': os.environ.get('SLO_OPENAI_API_KEY')}))\n"
    )
    path.chmod(0o755)


def _write_isolated_wrapper(*, path: Path, python_bin: Path, entry_launcher: Path) -> None:
    """Write the canonical wrapper bytes used by the supported installer.

    Args:
        path (Path): User launcher path.
        python_bin (Path): Validated venv interpreter.
        entry_launcher (Path): Generated packaging trampoline.
    """
    path.write_text(
        "#!/bin/sh\n"
        "# >>> slo isolated launcher (v1) >>>\n"
        "# Generated by the Slo installer; do not edit.\n"
        f"exec '{python_bin}' -I '{entry_launcher}' \"$@\"\n"
    )
    path.chmod(0o755)


class TestDirectPipxAndVersionedLauncherContract:
    """Artifact-state tests keep direct-pipx and historic rollback claims honest."""

    def test_direct_pipx_regeneration_leaves_plain_launcher_until_supported_finalizer(
        self, tmp_path: Path
    ) -> None:
        """A regenerated packaging script has no wrapper marker until the tagged repair finalizes it."""
        bin_dir: Path = tmp_path / "pipx-home" / "venvs" / "slo" / "bin"
        bin_dir.mkdir(parents=True)
        user_launcher: Path = bin_dir / "slo"
        entry_launcher: Path = bin_dir / "slo-entry"
        generated_script: str = f"#!{sys.executable}\nfrom src.cli import main\nmain()\n"
        user_launcher.write_text(generated_script)
        entry_launcher.write_text(generated_script)

        assert "slo isolated launcher" not in user_launcher.read_text()
        _write_isolated_wrapper(
            path=user_launcher, python_bin=Path(sys.executable), entry_launcher=entry_launcher
        )
        assert "slo isolated launcher" in user_launcher.read_text()

    def test_pre_82_rollback_has_plain_launcher_and_no_entry_trampoline(self, tmp_path: Path) -> None:
        """Historic rollback intentionally removes the isolation prerequisite rather than faking compatibility."""
        bin_dir: Path = tmp_path / "pre-82" / "bin"
        bin_dir.mkdir(parents=True)
        user_launcher: Path = bin_dir / "slo"
        user_launcher.write_text(f"#!{sys.executable}\nfrom src.cli import main\nmain()\n")

        assert not (bin_dir / "slo-entry").exists()
        assert "slo isolated launcher" not in user_launcher.read_text()

    def test_reinstalling_82_a_regenerates_then_restores_the_wrapper(self, tmp_path: Path) -> None:
        """An 82.a-to-82.a supported reinstall restores the wrapper after replacing generated scripts."""
        bin_dir: Path = tmp_path / "pipx-home" / "venvs" / "slo" / "bin"
        bin_dir.mkdir(parents=True)
        user_launcher: Path = bin_dir / "slo"
        entry_launcher: Path = bin_dir / "slo-entry"
        generated_script: str = f"#!{sys.executable}\nfrom src.cli import main\nmain()\n"
        user_launcher.write_text(generated_script)
        entry_launcher.write_text(generated_script)
        _write_isolated_wrapper(
            path=user_launcher, python_bin=Path(sys.executable), entry_launcher=entry_launcher
        )

        user_launcher.write_text(generated_script)
        assert "slo isolated launcher" not in user_launcher.read_text()
        _write_isolated_wrapper(
            path=user_launcher, python_bin=Path(sys.executable), entry_launcher=entry_launcher
        )

        assert "slo isolated launcher" in user_launcher.read_text()


class TestIsolatedLauncherFunctional:
    """The installer-produced wrapper process owns hostile-import resistance."""

    def test_finalizer_generated_wrapper_ignores_foreign_pythonpath_and_preserves_slo_environment(
        self, tmp_path: Path
    ) -> None:
        """The real finalizer writer produces the wrapper executed by the hostile probe."""
        fake_bin = FakeBin(root=tmp_path / "fixture")
        pipx_home: Path = tmp_path / "fixture" / "pipx-home"
        venv_root, python_bin, wrapper, entry_launcher = fake_bin.make_launcher_layout(pipx_home=pipx_home)
        location: Path = venv_root / "site-packages"
        location.mkdir()
        fake_bin.write_fake_pipx(location=location, pipx_home=pipx_home)

        probe: Path = tmp_path / "fixture" / "probe-python"
        probe.write_text(f"#!/bin/sh\nprintf '%s\\n' '{venv_root}'\nexec '{sys.executable}' \"$@\"\n")
        probe.chmod(0o755)
        python_bin.unlink()
        python_bin.symlink_to(probe)

        finalized = fake_bin.run(snippet="slo_finalize_isolated_launcher")
        _write_entry_launcher(path=entry_launcher, python_bin=python_bin)

        assert finalized.returncode == 0, finalized.stderr
        wrapper_bytes: bytes = wrapper.read_bytes()
        assert wrapper_bytes == (
            b"#!/bin/sh\n"
            b"# >>> slo isolated launcher (v1) >>>\n"
            b"# Generated by the Slo installer; do not edit.\n"
            + f"exec '{python_bin}' -I '{entry_launcher}' \"$@\"\n".encode()
        )

        foreign_root: Path = tmp_path / "fixture" / "foreign"
        (foreign_root / "src").mkdir(parents=True)
        (foreign_root / "src" / "cli.py").write_text("raise RuntimeError('foreign src selected')\n")
        (foreign_root / "config").mkdir()
        (foreign_root / "config" / "cfg.py").write_text("raise RuntimeError('foreign config selected')\n")
        (foreign_root / "slo").mkdir()
        (foreign_root / "slo" / "__init__.py").write_text("raise RuntimeError('foreign slo selected')\n")
        environment: dict[str, str] = dict(os.environ) | {
            "PYTHONPATH": str(foreign_root),
            "SLO_HOME": str(tmp_path / "fixture" / "slo-home"),
            "SLO_SKILLS_DIR": str(tmp_path / "fixture" / "slo-skills"),
            "SLO_KB_DIR": str(tmp_path / "fixture" / "slo-kb"),
            "SLO_OPENAI_API_KEY": "secret-is-visible-to-initial-process",
        }
        completed: subprocess.CompletedProcess[str] = subprocess.run(
            [str(wrapper)],
            cwd=foreign_root,
            env=environment,
            capture_output=True,
            text=True,
            check=False,
        )

        assert completed.returncode == 0, completed.stderr
        assert str(foreign_root) not in completed.stdout
        assert f'"slo_home": "{tmp_path / "fixture" / "slo-home"}"' in completed.stdout
        assert f'"skills_dir": "{tmp_path / "fixture" / "slo-skills"}"' in completed.stdout
        assert f'"kb_dir": "{tmp_path / "fixture" / "slo-kb"}"' in completed.stdout
        assert '"credential": "secret-is-visible-to-initial-process"' in completed.stdout
