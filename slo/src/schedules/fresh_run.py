class FreshRunCommand:
    """The one owner of the headless fresh-run command line and environment.

    Every scheduled headless start gets its argv, working directory, ``slo``
    executable and child environment from this one policy object; nothing else
    under ``src/schedules`` builds a ``slo run`` command line (111.a.3 A9).
    """

    def __init__(
        self,
        *,
        venv_bin_dir: Optional[Path] = None,
        path_lookup: Callable[[str], Optional[str]] = shutil.which,
    ) -> None:
        """Bind the executable-lookup inputs.

        Args:
            venv_bin_dir (Optional[Path]): The directory holding the virtualenv
                ``slo`` binary; defaults to the running interpreter's bin dir,
                resolved as a directory without following the interpreter file:
                a virtualenv's ``bin/python`` is a symlink to the base
                interpreter, whose directory holds no virtualenv ``slo``.
            path_lookup (Callable[[str], Optional[str]]): Resolves a name on
                ``PATH``; ``shutil.which`` in production.
        """
        self._venv_bin_dir: Path = (
            venv_bin_dir if venv_bin_dir is not None else Path(sys.executable).absolute().parent.resolve()
        )
        self._path_lookup: Callable[[str], Optional[str]] = path_lookup

    def argv(self, *, prompt: str, cwd: Optional[str], model: Optional[str], session_id: str) -> list[str]:
        """Build the headless ``slo run`` argv for one fresh run.

        The located wrapper is started through `isolated_start`, so a hostile
        cwd or PYTHONPATH cannot select a planted module (111.a.3 A11).

        Args:
            prompt (str): The schedule prompt.
            cwd (Optional[str]): The schedule's working directory override.
            model (Optional[str]): The schedule's model override.
            session_id (str): The minted session id for this run.

        Returns:
            list[str]: The full child argv.

        Raises:
            FileNotFoundError: When no ``slo`` executable resolves.
            UnsupportedFreshRunWrapperError: When the wrapper cannot be started isolated.
        """
        argv: list[str] = self.isolated_start(wrapper=self.locate_executable())
        argv.extend(["run", "--prompt", prompt, "--json"])
        if cwd is not None:
            argv.extend(["--cwd", cwd])
        if model is not None:
            argv.extend(["--model", model])
        argv.extend(["--session-id", session_id])
        return argv

    def isolated_start(self, *, wrapper: Path) -> list[str]:
        """Return the argv prefix that starts one wrapper with import isolation.

        Only the two supported installed shapes are accepted. The installer's
        isolated launcher already execs ``python -I`` and runs directly; a
        packaging-generated console script runs under its own interpreter with
        ``-I``. Anything else (a shell shim, an ``env`` shebang, a launcher
        without ``-I``) could import from a hostile cwd or PYTHONPATH, so it is
        refused rather than started (111.a.3 A11).

        Args:
            wrapper (Path): The resolved ``slo`` wrapper.

        Returns:
            list[str]: The argv prefix that starts the wrapper isolated.

        Raises:
            UnsupportedFreshRunWrapperError: When the wrapper is neither supported shape.
        """
        lines: list[str] = self._wrapper_lines(wrapper=wrapper)
        if self._is_installer_launcher(lines=lines):
            return [str(wrapper)]
        console_script: Optional[re.Match[str]] = _CONSOLE_SCRIPT_SHEBANG.match(lines[0]) if lines else None
        if console_script is not None:
            return [console_script.group(1), "-I", str(wrapper)]
        raise UnsupportedFreshRunWrapperError(
            f"Refusing to start {wrapper}: it is neither the installer's isolated launcher "
            "nor a console script with an absolute python interpreter."
        )

    def _wrapper_lines(self, *, wrapper: Path) -> list[str]:
        """Read one wrapper's text lines; an unreadable wrapper has none.

        Args:
            wrapper (Path): The resolved ``slo`` wrapper.

        Returns:
            list[str]: The wrapper's lines, or an empty list when unreadable.
        """
        try:
            return wrapper.read_text(encoding="utf-8", errors="replace").splitlines()
        except OSError:
            return []

    def _is_installer_launcher(self, *, lines: list[str]) -> bool:
        """Tell whether wrapper lines are exactly the installer's isolated launcher.

        Args:
            lines (list[str]): The wrapper's lines.

        Returns:
            bool: True for the canonical four-line launcher with ``-I``.
        """
        return (
            len(lines) == 4
            and tuple(lines[:3]) == _INSTALLER_LAUNCHER_HEADER
            and _INSTALLER_LAUNCHER_EXEC.match(lines[3]) is not None
        )

    def working_directory(self, *, cwd: Optional[str]) -> str:
        """Resolve the child working directory to an absolute path.

        Args:
            cwd (Optional[str]): The schedule's working directory override.

        Returns:
            str: The absolute working directory for the child.
        """
        if cwd is None:
            return str(Path.cwd())
        return str(Path(cwd).expanduser().resolve())

    def locate_executable(self) -> Path:
        """Resolve the ``slo`` executable: virtualenv binary first, then ``PATH``.

        Returns:
            Path: Absolute executable path.

        Raises:
            FileNotFoundError: When neither lookup resolves, so no silent
                fallback to a nonexistent path can happen.
        """
        venv_candidate: Path = self._venv_bin_dir / "slo"
        if (
            venv_candidate.is_file()
            and not venv_candidate.is_symlink()
            and os.access(venv_candidate, os.X_OK)
        ):
            return venv_candidate
        which_result: Optional[str] = self._path_lookup("slo")
        if which_result is not None:
            return Path(which_result).resolve()
        raise FileNotFoundError("Could not resolve the slo executable.")

    def child_environment(self) -> dict[str, str]:
        """Copy inherited settings without pane ownership for scheduled children.

        Returns:
            dict[str, str]: All inherited values except ``HERDR_``-prefixed
                names in any letter case.
        """
        return {key: value for key, value in os.environ.items() if not key.upper().startswith("HERDR_")}


class SubprocessFreshRunLauncher:
    """Spawns the headless ``slo run`` child through ``asyncio.create_subprocess_exec``.

    The child never outlives `run`: when the wait ends early (cancellation,
    including repeated cancellation while the reap runs), the child is sent
    terminate, given a bounded grace to exit, then killed, and `run` returns
    only after it has been waited for (111.a.3 §5.6).
    """

    def __init__(self, *, command: Optional[FreshRunCommand] = None) -> None:
        """Bind the command policy that owns argv and child environment.

        Args:
            command (Optional[FreshRunCommand]): The command policy; defaults
                to the standard one.
        """
        self._command: FreshRunCommand = command if command is not None else FreshRunCommand()

    async def run(self, *, argv: list[str], cwd: str) -> int:
        """Run one child process to completion, reaping it if the wait ends early.

        Args:
            argv (list[str]): The full child argv.
            cwd (str): The working directory for the child.

        Returns:
            int: The child exit code (negative for a signal exit).

        Raises:
            asyncio.CancelledError: After the cancelled child has been reaped.
        """
        process: asyncio.subprocess.Process = await asyncio.create_subprocess_exec(
            *argv,
            env=self._command.child_environment(),
            stdout=asyncio.subprocess.DEVNULL,
            stderr=asyncio.subprocess.DEVNULL,
            cwd=cwd,
        )
        try:
            exit_code: int = await process.wait()
        except BaseException:
            await self._reap_whatever_cancels(process=process)
            raise
        return exit_code

    async def _reap_whatever_cancels(self, *, process: asyncio.subprocess.Process) -> None:
        """Own the reap as one task and wait for all of it despite cancellation.

        Further cancellations of the caller while the reap runs are absorbed
        here — the caller re-raises its original cancellation once the reap
        ends — so they can neither cut the child's grace nor leave a reap task
        behind.

        Args:
            process (asyncio.subprocess.Process): The child to stop.
        """
        reap: asyncio.Task[None] = asyncio.create_task(self._terminate_then_kill(process=process))
        while not reap.done():
            try:
                await asyncio.shield(reap)
            except asyncio.CancelledError:
                continue
        reap.result()

    async def _terminate_then_kill(self, *, process: asyncio.subprocess.Process) -> None:
        """Terminate one child, kill it past the grace, and wait for its exit.

        If the reap itself is cancelled (a loop-wide cancel at shutdown), the
        kill is still sent so a terminate-resistant child cannot survive.

        Args:
            process (asyncio.subprocess.Process): The child to stop.
        """
        if process.returncode is not None:
            return
        with suppress(ProcessLookupError):
            process.terminate()
        try:
            await asyncio.wait_for(process.wait(), timeout=_REAP_GRACE_SECONDS)
        except asyncio.TimeoutError:
            pass
        finally:
            if process.returncode is None:
                with suppress(ProcessLookupError):
                    process.kill()
        await process.wait()


class FreshRunInvoker:
    """Builds the headless ``slo run`` command for one fresh run and waits for it."""

    def __init__(self, *, launcher: FreshRunLauncher, command: Optional[FreshRunCommand] = None) -> None:
        """Bind the launcher and the command policy this invoker uses.

        Args:
            launcher (FreshRunLauncher): The child-process launcher.
            command (Optional[FreshRunCommand]): The command policy; defaults
                to the standard one.
        """
        self._launcher: FreshRunLauncher = launcher
        self._command: FreshRunCommand = command if command is not None else FreshRunCommand()

    async def start(
        self,
        *,
        prompt: str,
        cwd: Optional[str],
        model: Optional[str],
        session_id: str,
    ) -> FreshRunResultDAO:
        """Start one headless fresh run and wait for it.

        Args:
            prompt (str): The schedule prompt.
            cwd (Optional[str]): The schedule's working directory override.
            model (Optional[str]): The schedule's model override.
            session_id (str): The minted session id for this run.

        Returns:
            FreshRunResultDAO: The run result with the child's exit code.
        """
        argv: list[str] = self._command.argv(prompt=prompt, cwd=cwd, model=model, session_id=session_id)
        exit_code: int = await self._launcher.run(argv=argv, cwd=self._command.working_directory(cwd=cwd))
        return FreshRunResultDAO(
            session_id=session_id,
            exit_code=exit_code,
            status="completed" if exit_code == 0 else "run_failed",
        )
