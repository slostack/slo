"""Dev-time CLI: regenerate ``skills/INDEX.md`` from the committed skills tree.

Run by a developer after adding or editing a vendored skill:

    make build-skill-index

This script recursively reads the current ``skills/**/SKILL.md`` tree,
parses its YAML frontmatter (via ``SkillRegistry.load``), and rewrites only
``skills/INDEX.md``. Authored skill files are the source of truth. Runtime
manifest loading remains separate and unchanged.

``make refresh-skills`` delegates here too; neither command imports upstream
prompts or rewrites skill content. Never invoked at runtime.
"""

from __future__ import annotations

import sys
from pathlib import Path

from src.agents.skills.registry import SkillRegistry

_INDEX_HEADER = """\
# Slo Skills Index

This file lists the bundled skills available to the slo agent.
Start with `skills/engineering/engineering-routing/SKILL.md` for layered selection.
Installed user skills/workflows also appear in the runtime manifest; same-name
user entries override bundled entries. This index is not the complete installed catalog. The agent reads this
index on demand (via the `read` tool) when a task starts; when a task matches
a skill's description and routing hints, the agent then reads that skill's
`SKILL.md` and follows its instructions.

Each skill below is a markdown file with YAML frontmatter (`name`,
`description`, `when_to_use`, `group`, `kind`) plus an instructional body.
The index is grouped into **Workflows** and **Individual Skills**, then
split by category.

> **Note:** this file is regenerated by `make build-skill-index` from the
> current `skills/**/SKILL.md` tree. Edit the SKILL.md files
> (not this index) when adding or revising a skill, then re-run the
> regenerator.

"""


def _resolve_skills_dir() -> Path:
    """Return the absolute path to ``slo/skills/``."""
    return (Path(__file__).resolve().parent.parent / "skills").resolve()


def main() -> int:
    """Regenerate ``skills/INDEX.md`` and print a one-line summary."""
    skills_dir = _resolve_skills_dir()
    if not skills_dir.is_dir():
        print(f"error: skills directory not found at {skills_dir}", file=sys.stderr)
        return 1

    skills = SkillRegistry.load(skills_dir=skills_dir)
    if not skills:
        print(f"warning: no skills found under {skills_dir}", file=sys.stderr)

    body = SkillRegistry.format_for_prompt(skills=skills)
    index_path = skills_dir / "INDEX.md"
    index_path.write_text(_INDEX_HEADER + body, encoding="utf-8")

    print(f"wrote {index_path} ({len(skills)} skill{'s' if len(skills) != 1 else ''})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
