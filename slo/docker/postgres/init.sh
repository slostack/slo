#!/bin/bash
set -e

until psql -c '\l'; do
  echo "Postgres is unavailable - sleeping"
  sleep 1
done

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOSQL
    CREATE USER $SLO_APP_DB_USER WITH PASSWORD '$SLO_APP_DB_PASS';
EOSQL

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOSQL
    CREATE DATABASE $SLO_APP_DB_NAME;
EOSQL

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOSQL
    GRANT ALL PRIVILEGES ON SCHEMA public TO $SLO_APP_DB_USER;
EOSQL

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOSQL
    GRANT CREATE ON DATABASE $SLO_APP_DB_NAME TO $SLO_APP_DB_USER;
    ALTER DATABASE $SLO_APP_DB_NAME OWNER TO $SLO_APP_DB_USER;
    GRANT USAGE ON SCHEMA public TO $SLO_APP_DB_USER;
    GRANT USAGE ON ALL SEQUENCES IN SCHEMA public TO $SLO_APP_DB_USER;
    GRANT USAGE, CREATE ON SCHEMA public TO $SLO_APP_DB_USER;
    GRANT CONNECT ON DATABASE $SLO_APP_DB_NAME TO $SLO_APP_DB_USER;
    GRANT ALL PRIVILEGES ON DATABASE $SLO_APP_DB_NAME TO $SLO_APP_DB_USER;
EOSQL

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOSQL
    \c $SLO_APP_DB_NAME
    CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
    CREATE EXTENSION IF NOT EXISTS "vector";
EOSQL
